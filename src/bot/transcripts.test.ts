/**
 * Transcript fixtures: run scripted conversations through the real engine + the mock OneEPC and write them as
 * readable Markdown under src/bot/transcripts/ (for Nabil to review). The files are snapshots: if a template or the
 * flow changes, this test fails until the Markdown is regenerated with `npx vitest run -u src/bot/transcripts.test.ts`
 * and the diff is reviewed.
 */
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import { Conversation } from "./conversation-driver.js";
import { findPartNumberLikeTokens } from "./guard.js";
import { failing, recording, startMock } from "./testkit.js";

let mock: Awaited<ReturnType<typeof startMock>>;
beforeAll(async () => {
  mock = await startMock();
});
afterAll(async () => {
  await mock.close();
});

const LC = "TESTLC20220000001";
const TUCSON = "TESTHY20210000002";
const HILUX = "TESTAMB2020000003";

type Script = { title: string; note: string; messages: string[]; silentOk?: number[]; shop?: Record<string, unknown> };

const GULF: Script[] = [
  {
    title: "1. Part first, then the VIN (Tucson)",
    note: "Mock vehicle: TESTHY… = Hyundai Tucson. The customer says Camry in message 1: the bot does not use the model from free text, only the VIN.",
    messages: ["السلام عليكم ابغى فحمات قدام لكامري ٢٠٢٠", `هذا الشاصي ${TUCSON}`, "شكرا"],
    silentOk: [2],
  },
  {
    title: "2. Greeting, then a part, then the VIN, then another part (Land Cruiser)",
    note: "Oil filter: the API also returns the air filter at 0.5 and the bot does not quote it (threshold 0.6).",
    messages: ["هلا", "عندكم فلتر زيت؟", LC, "وفلتر هواء", "يعطيك العافية"],
    silentOk: [4],
  },
  {
    title: "3. Ambiguous VIN (Hilux): variant question, pick by number",
    note: "The bot never picks a variant by itself.",
    messages: ["مساء الخير", "ابي فلتر زيت لهايلكس", HILUX, "الثاني"],
  },
  {
    title: "4. Unclear variant answer, then pick by engine",
    note: "",
    messages: [HILUX, "مدري", "4.0 ست سلندر", "فلتر زيت"],
  },
  {
    title: "5. Price question and off-topic",
    note: "No prices at all in this step. The price word is dropped from the search text; the part number is quoted, nothing else.",
    messages: [`كم سعر فلتر الزيت ${LC}`, "وش رايك في الاسهم اليوم"],
  },
  {
    title: "6. Customer wants a person",
    note: "",
    messages: ["ابي اكلم موظف", "هلا؟"],
    silentOk: [1],
  },
];

describe("Gulf Arabic transcripts", () => {
  it("12+ short messages: at most one bot message each, one for every non-silent turn, and no unverified part numbers", async () => {
    const rec = recording(mock.client);
    const md: string[] = [
      "# Gulf Arabic conversations (generated by `src/bot/transcripts.test.ts`)",
      "",
      "Real engine, mock OneEPC (part numbers are the mock's `00000-EXAMPLEn`), no WhatsApp, no LLM. Opening hours are the placeholder defaults, 09:00 Sunday Riyadh time.",
      "",
    ];
    let customerMessages = 0;
    for (const s of GULF) {
      const c = new Conversation(rec, s.shop ?? {});
      for (const [i, m] of s.messages.entries()) {
        const before = c.turns.filter((t) => t.from === "bot").length;
        await c.say(m);
        customerMessages++;
        const sent = c.turns.filter((t) => t.from === "bot").length - before;
        expect(sent, `${s.title} / message ${i + 1}`).toBeLessThanOrEqual(1);
        if (!(s.silentOk ?? []).includes(i)) expect(sent, `${s.title} / message ${i + 1}`).toBe(1);
      }
      for (const t of c.turns.filter((x) => x.from === "bot")) {
        for (const tok of findPartNumberLikeTokens(t.text)) expect(rec.partNumbers.has(tok), `unverified number ${tok}`).toBe(true);
        expect(t.text).not.toMatch(/ريال|سعر\b|SAR/);
      }
      md.push(c.toMarkdown(s.title, s.note || undefined), "---", "");
    }
    expect(customerMessages).toBeGreaterThanOrEqual(12);
    await expect(md.join("\n")).toMatchFileSnapshot("./transcripts/gulf-arabic.md");
  });
});

describe("Scenario transcripts", () => {
  it("core scenarios, readable", async () => {
    const md: string[] = ["# Core scenarios (generated by `src/bot/transcripts.test.ts`)", ""];

    const exact = new Conversation(mock.client);
    for (const m of ["السلام عليكم ابغى فلتر زيت", LC]) await exact.say(m);
    md.push(exact.toMarkdown("A. Exact VIN: confirmed part is quoted", "Quoted only because fitment is `confirmed` and the search is not ambiguous."), "---", "");

    const cond = new Conversation(mock.client);
    for (const m of [`${LC} فحمات قدام`, "17"]) await cond.say(m);
    md.push(
      cond.toMarkdown(
        "B. Ambiguous / conditional fitment: never says it fits",
        "The API's own question is asked. The mock never resolves the ambiguity, so the bot hands off instead of quoting a conditional part.",
      ),
      "---",
      "",
    );

    const unknown = new Conversation(mock.client);
    for (const m of [`${"TESTNF00000000004"} فلتر زيت`, "فيه أحد؟"]) await unknown.say(m);
    md.push(unknown.toMarkdown("C. Unknown VIN: handoff, then silence"), "---", "");

    const en = new Conversation(mock.client);
    for (const m of ["hi, I need front brake pads", TUCSON]) await en.say(m);
    md.push(en.toMarkdown("D. English customer"), "---", "");

    const err = new Conversation(failing(503, "upstream_unavailable"));
    await err.say(`${LC} فلتر زيت`);
    md.push(err.toMarkdown("E. OneEPC down (503): safe handoff", "The customer never sees the upstream error; ops get an alert action."), "---", "");

    const cap = new Conversation(mock.client, { maxBotMessagesPerDay: 2 });
    for (const m of ["ابغى فلتر زيت", LC, "وفلتر هواء", "هلا"]) await cap.say(m);
    md.push(cap.toMarkdown("F. Daily cap reached: one final message, then silence (cap = 2 for this demo)"), "---", "");

    await expect(md.join("\n")).toMatchFileSnapshot("./transcripts/scenarios.md");
  });
});
